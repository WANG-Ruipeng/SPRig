#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Evaluate skeleton consistency metrics (PJDD and GSD) on the DeformingThings4D
fine-tuning dataset NPZ.

This script is intended for the SPRig supplementary pipeline:
- The NPZ is generated by build_finetune_dataset.py with
  --anchor_criterion {area|bbox_volume}.
- The dataset builder selects `best_anchor_idx` and reorders keyframes so that
  keyframe[0] is always the anchor frame.
- A SkeletonGPT checkpoint is run on each keyframe, and the decoded joints are
  used to compute:
    * PJDD: Pairwise Joint Distance Deviation
    * GSD:  Graph Spectral Discrepancy

Metrics are first averaged across non-anchor keyframes within each sequence
and then averaged across sequences. Rigid Procrustes alignment is used by
default; pass --procrustes_scale to enable similarity alignment.
"""

from __future__ import annotations

import argparse
import json
import os
from typing import Any, Dict, List, Optional, Tuple

import numpy as np
import torch
from torch.utils.data import DataLoader, Dataset
from transformers.generation.logits_process import LogitsProcessor, LogitsProcessorList

from skeleton_gpt_finetune import SkeletonGPT


class DT4DKeyframeNPZ(Dataset):
    def __init__(self, npz_path: str, seq_list: Optional[List[str]] = None, only_seq: Optional[str] = None):
        self.npz_path = npz_path
        pack = np.load(npz_path, allow_pickle=True)
        if "sequences" not in pack:
            raise KeyError(f"{npz_path} missing key 'sequences'. keys={list(pack.keys())}")
        seqs = list(pack["sequences"])

        items: List[Dict[str, Any]] = []
        for s in seqs:
            if isinstance(s, dict):
                d = s
            elif hasattr(s, "item"):
                d = s.item()
            else:
                raise TypeError(f"Unexpected sequence entry type: {type(s)}")

            sid = d.get("sequence_id", None)
            if sid is None:
                continue
            if only_seq is not None and sid != only_seq:
                continue
            if seq_list is not None and sid not in seq_list:
                continue
            items.append(d)

        self.items = items

    def __len__(self) -> int:
        return len(self.items)

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        d = self.items[idx]
        pc = d.get("keyframe_pointclouds", None)
        if pc is None:
            pc = d.get("keyframe_meshes", None)
        if pc is None:
            raise KeyError(f"Sequence {d.get('sequence_id')} missing keyframe pointclouds.")

        pc = np.asarray(pc)
        if pc.ndim != 3 or pc.shape[-1] != 6:
            raise ValueError(f"{d.get('sequence_id')}: expected keyframes (K,N,6), got {pc.shape}")

        meta = {
            "sequence_id": d.get("sequence_id"),
            "best_anchor_idx": int(d.get("best_anchor_idx", -1)) if "best_anchor_idx" in d else None,
            "best_anchor_score": float(d.get("best_anchor_score", 0.0)) if "best_anchor_score" in d else None,
            "anchor_criterion": d.get("anchor_criterion", None),
            "keyframe_names": d.get("keyframe_names", d.get("keyframe_files", None)),
        }
        return {"pc": pc, "meta": meta}


def _collate(batch: List[Dict[str, Any]]) -> Dict[str, Any]:
    pcs = [torch.from_numpy(b["pc"]).to(torch.float16) for b in batch]
    metas = [b["meta"] for b in batch]
    pc_tensor = torch.stack(pcs, dim=0)
    return {"pc": pc_tensor, "meta": metas}


def undiscretize(
    t: torch.Tensor,
    low: float = -0.5,
    high: float = 0.5,
    num_discrete: int = 128,
) -> torch.Tensor:
    t = t.float() / float(num_discrete)
    return t * (high - low) + low


def decode_joints_parents_from_tokens(
    tokens_1d: torch.Tensor,
    n_discrete_size: int,
    pad_id: int = -1,
    repair: bool = True,
) -> Tuple[Optional[torch.Tensor], Optional[torch.Tensor]]:
    """
    Decode a one-dimensional token sequence into joints and parent indices.

    `tokens_1d` must already be mapped into the coordinate/parent space,
    i.e. special tokens have been removed and the +3 vocabulary offset has
    been subtracted.
    """
    cur = tokens_1d[tokens_1d != pad_id]
    if cur.numel() == 0:
        return None, None
    if repair and (cur.numel() % 4 != 0):
        cur = cur[: (cur.numel() // 4) * 4]
        if cur.numel() == 0:
            return None, None
    if cur.numel() % 4 != 0:
        return None, None

    data = cur.view(-1, 4)
    coords_ids = data[:, :3].clamp(0, n_discrete_size - 1)
    joints = undiscretize(coords_ids, -0.5, 0.5, n_discrete_size)
    parents = data[:, 3].long()
    return joints.to(torch.float32), parents


class BanTokenIdsProcessor(LogitsProcessor):
    def __init__(self, banned_ids):
        self.banned = [int(x) for x in banned_ids]

    def __call__(self, input_ids, scores):
        if len(self.banned) > 0:
            scores[:, self.banned] = float("-inf")
        return scores


def _trim_to_mod4_per_row(out_1d: torch.Tensor, pad_id: int) -> torch.Tensor:
    valid = out_1d[out_1d != pad_id]
    n = (valid.numel() // 4) * 4
    fixed = torch.full_like(out_1d, pad_id)
    if n > 0:
        fixed[:n] = valid[:n]
    return fixed


@torch.no_grad()
def generate_tokens(
    model: SkeletonGPT,
    pc_normal: torch.Tensor,
    *,
    beams_eval: int = 4,
    ignore_eos_stop: bool = True,
) -> torch.Tensor:
    """
    Generate token sequences from 6D point clouds.

    Returns tokens in coordinate/parent-id space, using pad_id=-1 so that the
    output can be passed directly to `decode_joints_parents_from_tokens`.
    """
    device = next(model.parameters()).device
    model.eval()
    amp = torch.cuda.is_available()

    with torch.cuda.amp.autocast(enabled=amp):
        point_feature = model.point_encoder.encode_latents(pc_normal.to(device))
        enc = model.process_point_feature(point_feature)
        gen_len = model.max_length - model.cond_length

        logits_processors = LogitsProcessorList()
        logits_processors.append(BanTokenIdsProcessor([0, 1, 2]))

        results = model.transformer.generate(
            inputs_embeds=enc,
            max_new_tokens=gen_len,
            num_beams=max(1, int(beams_eval)),
            do_sample=False,
            pad_token_id=model.pad_token_id,
            bos_token_id=model.bos_token_id,
            eos_token_id=None if ignore_eos_stop else model.eos_token_id,
            logits_processor=logits_processors,
        )

        out = results[:, 1:].clone()
        pad_id_internal = getattr(model, "pad_id", -1)

        out[out < 3] = pad_id_internal
        mask_real = (out != pad_id_internal)
        out[mask_real] -= 3

        fixed = out.clone()
        for i in range(fixed.shape[0]):
            fixed[i] = _trim_to_mod4_per_row(fixed[i], pad_id_internal)

        return fixed.long()


def procrustes_align(A: np.ndarray, B: np.ndarray, *, scale: bool = False) -> Optional[np.ndarray]:
    """
    Align B onto A using rigid Procrustes alignment.

    If `scale=True`, a single global scale factor is also estimated.
    """
    if A is None or B is None or len(A) == 0 or len(B) == 0:
        return None

    J = min(len(A), len(B))
    A0 = A[:J].astype(np.float64)
    B0 = B[:J].astype(np.float64)

    muA = A0.mean(axis=0, keepdims=True)
    muB = B0.mean(axis=0, keepdims=True)
    Ac = A0 - muA
    Bc = B0 - muB

    H = Bc.T @ Ac
    U, S, Vt = np.linalg.svd(H)
    R = U @ Vt
    if np.linalg.det(R) < 0:
        U[:, -1] *= -1
        R = U @ Vt

    if scale:
        varB = (Bc ** 2).sum()
        s = float(S.sum() / varB) if varB > 1e-12 else 1.0
    else:
        s = 1.0

    Baligned = (Bc @ R) * s + muA
    return Baligned.astype(np.float32)


def mst_edges_from_points(P: np.ndarray) -> List[Tuple[int, int]]:
    """Compute Euclidean MST edges with Prim's algorithm."""
    J = int(P.shape[0])
    if J <= 1:
        return []

    used = np.zeros(J, dtype=bool)
    used[0] = True
    edges: List[Tuple[int, int]] = []

    best_dist = np.full(J, np.inf, dtype=np.float64)
    best_parent = np.full(J, -1, dtype=np.int64)

    while used.sum() < J:
        u_idxs = np.where(used)[0]
        v_idxs = np.where(~used)[0]

        for v in v_idxs:
            d = np.linalg.norm(P[u_idxs] - P[v], axis=1)
            m = float(d.min())
            if m < best_dist[v]:
                best_dist[v] = m
                best_parent[v] = int(u_idxs[int(d.argmin())])

        v = int(v_idxs[int(best_dist[v_idxs].argmin())])
        u = int(best_parent[v])
        if u < 0:
            u = int(u_idxs[0])
        a, b = (u, v) if u < v else (v, u)
        edges.append((a, b))
        used[v] = True
        best_dist[v] = np.inf

    return edges


def pairwise_dists_sorted(P: np.ndarray) -> np.ndarray:
    """Compute all pairwise distances and sort them in ascending order."""
    J = int(P.shape[0])
    if J <= 1:
        return np.zeros((0,), dtype=np.float64)

    d = []
    for i in range(J):
        for j in range(i + 1, J):
            d.append(float(np.linalg.norm(P[i] - P[j])))
    d = np.asarray(d, dtype=np.float64)
    d.sort()
    return d


def edge_lengths_sorted(P: np.ndarray, edges: List[Tuple[int, int]]) -> np.ndarray:
    """Compute sorted edge lengths for a fixed edge set."""
    if len(edges) == 0 or P.shape[0] == 0:
        return np.zeros((0,), dtype=np.float64)

    L = []
    J = int(P.shape[0])
    for (u, v) in edges:
        if u >= J or v >= J:
            continue
        L.append(float(np.linalg.norm(P[u] - P[v])))
    L = np.asarray(L, dtype=np.float64)
    L.sort()
    return L


def normalized_laplacian_eigs(
    P: np.ndarray,
    edges: List[Tuple[int, int]],
    anchor_medlen: float,
    *,
    k_eigs: int = 8,
    eps: float = 1e-8,
) -> np.ndarray:
    """
    Build the normalized graph Laplacian on a fixed edge set and return the
    smallest `k_eigs` eigenvalues.
    """
    J = int(P.shape[0])
    if J <= 0 or len(edges) == 0:
        return np.zeros((k_eigs,), dtype=np.float64)

    scale = max(float(anchor_medlen), eps)
    W = np.zeros((J, J), dtype=np.float64)
    for (u, v) in edges:
        if u >= J or v >= J:
            continue
        w = float(np.linalg.norm(P[u] - P[v])) / scale
        W[u, v] = w
        W[v, u] = w

    d = W.sum(axis=1)
    d_safe = np.where(d > eps, d, 1.0)
    D_inv_sqrt = np.diag((1.0 / np.sqrt(d_safe)).astype(np.float64))
    I = np.eye(J, dtype=np.float64)
    L = I - (D_inv_sqrt @ W @ D_inv_sqrt)

    w, _ = np.linalg.eigh(L)
    w = np.sort(w)
    k = min(int(k_eigs), len(w))
    out = np.zeros((k_eigs,), dtype=np.float64)
    out[:k] = w[:k]
    if k < k_eigs:
        out[k:] = w[-1] if len(w) > 0 else 0.0
    return out


def pjdd_single(Dk: np.ndarray, D0: np.ndarray, *, eps: float = 1e-3) -> float:
    if Dk.size == 0 or D0.size == 0:
        return float("nan")
    n = min(Dk.size, D0.size)
    den = max(float(np.median(D0)), eps)
    return float(np.mean(np.abs(Dk[:n] - D0[:n])) / den)


def gsd_single(eigk: np.ndarray, eig0: np.ndarray) -> float:
    n = min(eigk.size, eig0.size)
    if n == 0:
        return float("nan")
    return float(np.mean(np.abs(eigk[:n] - eig0[:n])))


def load_skeletongpt(
    model_weights: str,
    *,
    llm: str = "facebook/opt-350m",
    n_discrete_size: int = 128,
    n_max_bones: int = 100,
    num_beams: int = 4,
    device: Optional[str] = None,
) -> SkeletonGPT:
    if device is None:
        device = "cuda" if torch.cuda.is_available() else "cpu"

    args = argparse.Namespace(
        input_pc_num=8192,
        num_beams=int(num_beams),
        llm=llm,
        pad_id=-1,
        n_discrete_size=int(n_discrete_size),
        n_max_bones=int(n_max_bones),
        dataset_path="",
        output_dir="",
        save_name="",
        seed=0,
        precision="fp16",
        batchsize_per_gpu=1,
        pretrained_weights=model_weights,
        hier_order=False,
        joint_token=True,
        seq_shuffle=False,
        do_sample=False,
    )

    model = SkeletonGPT(args).to(device)

    pkg = torch.load(model_weights, map_location="cpu")
    if isinstance(pkg, dict) and "model" in pkg and isinstance(pkg["model"], dict):
        state_dict = pkg["model"]
    else:
        state_dict = pkg

    mismatched_key = "transformer.model.decoder.embed_positions.weight"
    try:
        model_dict = model.state_dict()
        if mismatched_key in state_dict and mismatched_key in model_dict:
            if state_dict[mismatched_key].shape != model_dict[mismatched_key].shape:
                del state_dict[mismatched_key]
    except Exception:
        pass

    model.load_state_dict(state_dict, strict=False)

    model.bos_token_id = 0
    model.eos_token_id = 1
    model.pad_token_id = 2
    if hasattr(model, "pad_id"):
        model.pad_id = -1
    if hasattr(model, "transformer") and hasattr(model.transformer, "config"):
        cfg = model.transformer.config
        cfg.bos_token_id = 0
        cfg.eos_token_id = 1
        cfg.pad_token_id = 2

    model.eval()
    return model


def parse_args():
    ap = argparse.ArgumentParser("Evaluate PJDD/GSD on an NPZ keyframe dataset")
    ap.add_argument(
        "--npz_path",
        type=str,
        required=True,
        help="Path to finetune_deformingthings4d_dataset_{train|val}.npz",
    )
    ap.add_argument("--model_weights", type=str, required=True, help="SkeletonGPT weights (.pth)")
    ap.add_argument("--out_json", type=str, required=True, help="Output JSON path")
    ap.add_argument(
        "--seq_list",
        type=str,
        default=None,
        help="Optional text file listing sequence IDs to evaluate, one per line.",
    )
    ap.add_argument("--seq", type=str, default=None, help="Evaluate a single sequence only")
    ap.add_argument("--batch_size", type=int, default=8)
    ap.add_argument("--num_workers", type=int, default=2)
    ap.add_argument("--num_beams_eval", type=int, default=4)
    ap.add_argument("--k_eigs", type=int, default=8)
    ap.add_argument("--ignore_eos_stop", action=argparse.BooleanOptionalAction, default=True)
    ap.add_argument("--repair_decode", action=argparse.BooleanOptionalAction, default=True)
    ap.add_argument(
        "--procrustes_scale",
        action=argparse.BooleanOptionalAction,
        default=False,
        help="If True, use similarity Procrustes alignment; otherwise use rigid alignment.",
    )
    ap.add_argument("--limit", type=int, default=-1, help="Debug option: only evaluate the first N sequences")
    return ap.parse_args()


def main():
    args = parse_args()

    seq_list = None
    if args.seq_list is not None:
        with open(args.seq_list, "r") as f:
            seq_list = [ln.strip() for ln in f if ln.strip()]

    device = "cuda" if torch.cuda.is_available() else "cpu"
    if torch.cuda.is_available():
        torch.backends.cuda.matmul.allow_tf32 = True
        torch.backends.cudnn.allow_tf32 = True

    out_dir = os.path.dirname(args.out_json)
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    dataset = DT4DKeyframeNPZ(args.npz_path, seq_list=seq_list, only_seq=args.seq)
    if args.limit > 0:
        dataset.items = dataset.items[: args.limit]

    loader = DataLoader(
        dataset,
        batch_size=args.batch_size,
        shuffle=False,
        num_workers=args.num_workers,
        collate_fn=_collate,
    )

    model = load_skeletongpt(args.model_weights, num_beams=args.num_beams_eval, device=device)

    PJDD_all: List[float] = []
    GSD_all: List[float] = []
    per_seq: Dict[str, Dict[str, Any]] = {}
    num_fail = 0

    with torch.no_grad():
        for batch in loader:
            pc = batch["pc"].to(device)
            metas = batch["meta"]
            B, K, N, D = pc.shape

            tokens_flat = generate_tokens(
                model,
                pc.view(B * K, N, D),
                beams_eval=args.num_beams_eval,
                ignore_eos_stop=args.ignore_eos_stop,
            )
            tokens_all = tokens_flat.view(B, K, -1)

            for b in range(B):
                sid = metas[b].get("sequence_id", f"idx_{len(per_seq):06d}")

                joints_seq: List[Optional[np.ndarray]] = []
                for k in range(K):
                    jts, _ = decode_joints_parents_from_tokens(
                        tokens_all[b, k],
                        n_discrete_size=getattr(model, "n_discrete_size", 128),
                        pad_id=getattr(model, "pad_id", -1),
                        repair=args.repair_decode,
                    )
                    joints_seq.append(None if jts is None else jts.cpu().numpy())

                J0 = joints_seq[0]
                if J0 is None or len(J0) <= 1:
                    per_seq[sid] = {"ok": False, "reason": "empty_anchor", "meta": metas[b]}
                    num_fail += 1
                    continue

                E0 = mst_edges_from_points(J0)
                L0 = edge_lengths_sorted(J0, E0)
                D0 = pairwise_dists_sorted(J0)
                if L0.size == 0 or D0.size == 0:
                    per_seq[sid] = {"ok": False, "reason": "degenerate_anchor", "meta": metas[b]}
                    num_fail += 1
                    continue

                anchor_medlen = float(np.median(L0))
                eig0 = normalized_laplacian_eigs(J0, E0, anchor_medlen, k_eigs=args.k_eigs)

                pj_list: List[float] = []
                gs_list: List[float] = []
                for k in range(1, K):
                    Jk = joints_seq[k]
                    if Jk is None or len(Jk) <= 1:
                        continue
                    Jk_aligned = procrustes_align(J0, Jk, scale=args.procrustes_scale)
                    if Jk_aligned is None:
                        continue

                    Dk = pairwise_dists_sorted(Jk_aligned)
                    pj = pjdd_single(Dk, D0)
                    if not np.isnan(pj):
                        pj_list.append(pj)

                    eigk = normalized_laplacian_eigs(Jk_aligned, E0, anchor_medlen, k_eigs=args.k_eigs)
                    gs = gsd_single(eigk, eig0)
                    if not np.isnan(gs):
                        gs_list.append(gs)

                if len(pj_list) == 0 or len(gs_list) == 0:
                    per_seq[sid] = {"ok": False, "reason": "empty_non_anchor", "meta": metas[b]}
                    num_fail += 1
                    continue

                pjdd = float(np.mean(pj_list))
                gsd = float(np.mean(gs_list))
                PJDD_all.append(pjdd)
                GSD_all.append(gsd)

                per_seq[sid] = {
                    "ok": True,
                    "pjdd": pjdd,
                    "gsd": gsd,
                    "num_keyframes": int(K),
                    "meta": metas[b],
                }

    def safe_mean(xs: List[float]) -> float:
        return float(np.mean(xs)) if len(xs) > 0 else 0.0

    summary = {
        "num_seq": len(dataset),
        "num_ok": len(PJDD_all),
        "num_fail": int(num_fail),
        "pjdd_mean": safe_mean(PJDD_all),
        "gsd_mean": safe_mean(GSD_all),
    }

    out = {
        "args": vars(args),
        "summary": summary,
        "per_sequence": per_seq,
    }

    with open(args.out_json, "w") as f:
        json.dump(out, f, indent=2)


if __name__ == "__main__":
    main()
